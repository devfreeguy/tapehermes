const key = 'tapehermes-locale'
export const message = (text, ...values) => ({ text, values })

export function format(locale, value) {
  if (value?.literal !== undefined) return String(value.literal)
  if (locale === 'en' && value?.english !== undefined) return String(value.english)
  const { text, values } = typeof value === 'object' && value?.values ? value : message(value)
  const template = locale === 'zh-CN' && Object.hasOwn(chinese, text) ? chinese[text] : text
  return values.length ? template.replace(/\{(\d+)\}/g, (_, index) => format(locale, values[index])) : String(template ?? '')
}

export function createLocale(doc, win) {
  const read = () => {
    try { return win.localStorage.getItem(key) } catch { return null }
  }
  let locale = read() === 'en' ? 'en' : 'zh-CN'
  const bindings = new WeakMap()
  const staticCopy = [...doc.querySelectorAll('[data-en], [data-en-label], [data-en-content]')].map((node) => ({
    node, text: node.hasAttribute('data-en') ? node.textContent : null,
    label: node.getAttribute('aria-label'), content: node.getAttribute('content'),
  }))
  const menu = doc.getElementById('language-switch')
  const options = [...menu.querySelectorAll('[data-language]')]

  function write(node, values) {
    for (const [attr, value] of values) {
      const text = format(locale, value)
      if (attr) node.setAttribute(attr, text)
      else node.textContent = text
    }
  }

  function render() {
    doc.documentElement.lang = locale
    for (const { node, text, label, content } of staticCopy) {
      if (node.hasAttribute('data-en')) node.textContent = locale === 'en' ? node.dataset.en : text
      if (node.hasAttribute('data-en-label')) node.setAttribute('aria-label', locale === 'en' ? node.dataset.enLabel : label)
      if (node.hasAttribute('data-en-content')) node.setAttribute('content', locale === 'en' ? node.dataset.enContent : content)
    }
    for (const option of options) option.setAttribute('aria-pressed', String(option.dataset.language === locale))
    for (const node of doc.querySelectorAll('[data-live-copy]')) {
      const values = bindings.get(node)
      if (values) write(node, values)
    }
  }

  for (const option of options) option.addEventListener('click', () => {
    locale = option.dataset.language
    try { win.localStorage.setItem(key, locale) } catch { /* Keep the selection for this page. */ }
    render()
    menu.open = false
    menu.querySelector('summary').focus()
  })
  menu.addEventListener('keydown', (event) => {
    if (event.key !== 'Escape' || !menu.open) return
    menu.open = false
    menu.querySelector('summary').focus()
  })
  doc.addEventListener('click', (event) => {
    if (!menu.contains(event.target)) menu.open = false
  })
  win.addEventListener('storage', (event) => {
    if (event.key !== key && event.key !== null) return
    locale = read() === 'en' ? 'en' : 'zh-CN'
    render()
  })
  render()

  return {
    copy(node, value, attr = '') {
      const values = bindings.get(node) ?? new Map()
      values.set(attr, value)
      bindings.set(node, values)
      node.dataset.liveCopy = ''
      write(node, values)
      return node
    },
  }
}

export function englishCopy(node, value, attr = '') {
  const text = format('en', value)
  if (attr) node.setAttribute(attr, text)
  else node.textContent = text
  return node
}
